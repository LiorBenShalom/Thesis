"""
M9 (LLM-best) pick PROVENANCE on 4,432.

Every M9 pick has an LLM score => its (q,c) pair was generated by SOME
retrieval method we ran (current or historical). "In NEITHER" (not in current
filtered-sup top-100, no citation link) does NOT mean "from nowhere" — it means
"reached only via another/older scored pool". This script attributes every
pick (esp. NEITHER) to its source batch(es), and verifies 0 picks have no source.

Sources (= the exact files rigor_phase_a loads):
  combined.csv.source_batch : main/extended/supp/retry1/retry2 (historical
                              pipeline pools) + supervised_4432_union (current)
  5fold, simcse, supervised_baseline, 5fold_v2, filtered (separate batch files)

Output: data/m9_picks_provenance_4432.csv  (per pick: domain,query,pick,
        category,sources)  + printed aggregate.
"""
from pathlib import Path
import numpy as np, pandas as pd
from collections import Counter

ROOT = Path("/Users/liorb/Library/CloudStorage/OneDrive-post.bgu.ac.il/Thesis!!!/new_try")
EXP  = ROOT / "experiments"
FILTERED_DIR = ROOT / "simcse_cuda_bundle/outputs_supervised_filtered"
OUT = Path(__file__).resolve().parent.parent / "data"
N_FOLDS, K, TOP_POOL = 5, 10, 100

sup = pd.read_csv(ROOT / "simcse_cuda_bundle/data/supervised_data.csv")
v_to_text = dict(zip(sup.verdict, sup.indictment_facts))
m = pd.read_csv(EXP / "data_per_domain/master_inventory.csv",
                usecols=["canonical_id","domain","sentencing_range_low",
                         "sentencing_confidence"])
m = m[m.domain.isin(["drugs","weapon"]) & m.sentencing_range_low.notna()
      & (m.sentencing_confidence == "גבוהה")].drop_duplicates("canonical_id")
rng_lo = set(m.canonical_id)

# ---- pair -> set of source labels (+ scalar score for ranking) ----
pair_src = {}        # (a,b) -> set(labels)
llm_scores = {}
def add(a, b, s, label):
    k = tuple(sorted([a, b]))
    llm_scores[k] = float(s)
    pair_src.setdefault(k, set()).add(label)

cmb = pd.read_csv(EXP / "data_per_domain/similarity_scores_combined.csv")
for r in cmb.itertuples(index=False):
    if pd.notna(r.similarity_score):
        lab = "current_union" if str(r.source_batch).startswith("supervised_4432_union") \
              else f"hist:{r.source_batch}"
        add(r.verdict_1, r.verdict_2, r.similarity_score, lab)
for path, lab in [
    ("similarity_batch_5fold/results/similarity_scores_5fold.csv", "5fold"),
    ("similarity_batch_simcse/results/similarity_scores_simcse.csv", "simcse"),
    ("similarity_batch_supervised/results/similarity_scores_supervised.csv", "supervised_baseline"),
    ("similarity_batch_5fold_v2/results/similarity_scores_5fold_v2.csv", "5fold_v2"),
    ("similarity_batch_filtered/results/similarity_scores_filtered.csv", "filtered"),
]:
    p = EXP / "data_per_domain" / path
    if not p.exists(): continue
    for r in pd.read_csv(p).itertuples(index=False):
        if pd.notna(r.similarity_score):
            add(r.verdict_1, r.verdict_2, r.similarity_score, lab)

cit_pairs = set()
cd = pd.read_csv(EXP / "data_per_domain/network_analysis/citation_pair_types.csv")
for r in cd.itertuples(index=False):
    if r.citation_type in ("1hop", "2hop", "cocite"):
        cit_pairs.add(tuple(sorted([r.verdict_1, r.verdict_2])))

rows = []
for dom in ("drugs", "weapon"):
    for f in range(1, N_FOLDS + 1):
        ep = FILTERED_DIR / f"verdict_embeddings_{dom}_topk_fold{f}_offenseFiltered.npy"
        ip = FILTERED_DIR / f"verdict_index_{dom}_topk_fold{f}_offenseFiltered.csv"
        if not ep.exists(): continue
        emb = np.load(ep); idx = pd.read_csv(ip)
        v2i = {v: i for i, v in enumerate(idx.verdict)}
        train_ids = idx[idx.split == "train"].verdict.tolist()
        test_ids  = idx[idx.split == "test"].verdict.tolist()
        tarr = np.array([v2i[v] for v in train_ids])
        for q in test_ids:
            if q not in rng_lo or q not in v_to_text or q not in v2i: continue
            qi = v2i[q]
            order = np.argsort(-(emb[qi] @ emb[tarr].T))
            sup100 = set(train_ids[i] for i in order[:TOP_POOL])
            cand = [(t, llm_scores.get(tuple(sorted([q, t]))))
                    for t in train_ids if t != q]
            cand = [(t, s) for t, s in cand if s is not None and t in rng_lo]
            cand.sort(key=lambda x: -x[1])
            if len(cand) < K: continue
            for c, _ in cand[:K]:
                pk = tuple(sorted([q, c]))
                i100 = c in sup100
                hcit = pk in cit_pairs
                cat = ("both" if i100 and hcit else "sup100_only" if i100
                       else "cit_only" if hcit else "NEITHER")
                srcs = sorted(pair_src.get(pk, []))
                rows.append({"domain": dom, "query": q, "pick": c,
                             "category": cat, "sources": "|".join(srcs),
                             "n_sources": len(srcs)})

df = pd.DataFrame(rows)
df.to_csv(OUT / "m9_picks_provenance_4432.csv", index=False)

print(f"total M9 picks: {len(df):,}  (queries: {df['query'].nunique():,})")
print(f"picks with ZERO known source: {(df.n_sources==0).sum()}  "
      f"(must be 0 — every LLM-scored pick came from some method)")
print("\ncategory split (all picks):")
print((df.category.value_counts(normalize=True)*100).round(1).to_string())

for dom in ("drugs", "weapon"):
    nb = df[(df.domain==dom) & (df.category=="NEITHER")]
    print(f"\n=== {dom.upper()} — NEITHER picks provenance (n={len(nb):,}) ===")
    print("  (a pick can appear in several sources; % of NEITHER picks present in each)")
    cnt = Counter()
    for s in nb.sources:
        for lab in s.split("|"):
            if lab: cnt[lab] += 1
    for lab, n in cnt.most_common():
        print(f"   {lab:24s} {n:6d}  ({n/len(nb)*100:5.1f}%)")
    print(f"   NEITHER picks with NO source: {(nb.n_sources==0).sum()} "
          f"({(nb.n_sources==0).mean()*100:.1f}%)")
print(f"\n✅ wrote {OUT/'m9_picks_provenance_4432.csv'}")
